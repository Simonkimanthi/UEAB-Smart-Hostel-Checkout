"""
PostgreSQL database connection management and schema initialization.
"""

import psycopg
from flask import current_app, g


# Return rows that support both named and positional access.
class HybridRow(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def hybrid_row(cursor):
    """Build rows compatible with the existing SQLite row access."""

    # Commands such as CREATE TABLE do not return result rows.
    if cursor.description is None:
        return tuple

    columns = [column.name for column in cursor.description]

    def create_row(values):
        return HybridRow(zip(columns, values))

    return create_row


class DatabaseConnection:
    """Provide the existing application query interface using Psycopg."""

    def __init__(self, connection):
        self.connection = connection
        self.last_rowcount = 0

    def execute(self, query, parameters=None):
        normalized = query.strip().upper()

        # Serialize critical write transactions using a PostgreSQL advisory lock.
        if normalized == "BEGIN IMMEDIATE":
            return self.connection.execute(
                "SELECT pg_advisory_xact_lock(68420117)"
            )

        # Preserve SQLite's changes() behavior for existing application logic.
        if normalized == "SELECT CHANGES()":
            return self.connection.execute(
                "SELECT %s AS changes",
                (self.last_rowcount,)
            )

        query = query.replace("?", "%s")
        cursor = self.connection.execute(query, parameters or ())
        self.last_rowcount = cursor.rowcount
        return cursor

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def get_db():
    """Return the PostgreSQL connection for the current application context."""

    if "db" not in g:
        database_url = current_app.config.get("DATABASE_URL")

        if not database_url:
            raise RuntimeError(
                "DATABASE_URL is missing. Configure the PostgreSQL "
                "connection in the application environment."
            )

        connection = psycopg.connect(
            database_url,
            connect_timeout=15,
            sslmode="require",
            row_factory=hybrid_row
        )

        g.db = DatabaseConnection(connection)

    return g.db


def close_db(_error=None):
    """Close the connection when the application context ends."""

    db = g.pop("db", None)

    if db is not None:
        db.close()


def init_db():
    """Create missing PostgreSQL tables and indexes without deleting records."""

    db = get_db()

    statements = [
        """
        CREATE TABLE IF NOT EXISTS staff (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            full_name TEXT NOT NULL,
            username TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            role TEXT NOT NULL
                CHECK (role IN ('admin', 'dean', 'security')),
            active INTEGER NOT NULL DEFAULT 1,
            created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS checkout_requests (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            reference TEXT NOT NULL UNIQUE,
            student_name TEXT NOT NULL,
            registration_number TEXT NOT NULL,
            phone TEXT NOT NULL,
            hostel TEXT NOT NULL,
            room_number TEXT NOT NULL,
            destination TEXT NOT NULL,
            departure_date TEXT NOT NULL,
            reason TEXT,
            status TEXT NOT NULL DEFAULT 'submitted',
            key_status TEXT NOT NULL DEFAULT 'pending',
            key_handled_by BIGINT,
            key_handled_at TEXT,
            payment_status TEXT,
            payment_reference TEXT,
            payment_due_date TEXT,
            key_remarks TEXT,
            exception_reason TEXT,
            approved_by BIGINT,
            approved_at TEXT,
            created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),

            FOREIGN KEY (key_handled_by) REFERENCES staff(id),
            FOREIGN KEY (approved_by) REFERENCES staff(id)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS gate_passes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            request_id BIGINT NOT NULL UNIQUE,
            token TEXT NOT NULL UNIQUE,
            issued_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
            used_at TEXT,
            used_by BIGINT,
            revoked INTEGER NOT NULL DEFAULT 0,

            FOREIGN KEY (request_id) REFERENCES checkout_requests(id),
            FOREIGN KEY (used_by) REFERENCES staff(id)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS audit_logs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            staff_id BIGINT,
            action TEXT NOT NULL,
            details TEXT,
            created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),

            FOREIGN KEY (staff_id) REFERENCES staff(id)
        )
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_staff_role_active
        ON staff(role, active)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_checkout_status_created
        ON checkout_requests(status, created_at)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_checkout_registration
        ON checkout_requests(registration_number)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_gate_pass_used_at
        ON gate_passes(used_at)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_gate_pass_revoked
        ON gate_passes(revoked)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_audit_created_at
        ON audit_logs(created_at)
        """
    ]

    try:
        for statement in statements:
            db.execute(statement)

        db.commit()

    except Exception:
        db.rollback()
        raise
